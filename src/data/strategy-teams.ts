export interface StrategyPresetPokemonRef {
  slot: number;
  pokemonSlug: string;
  abilityName: string;
  itemName: string;
  moveNames: string[];
  role: TeamRole;
  explanation: string;
}

export interface StrategyTeamPreset {
  id: string;
  name: string;
  slug: string;
  strategyType: StrategyType;
  format: StrategyTeam["format"];
  difficulty: StrategyTeam["difficulty"];
  tags: string[];
  shortDescription: string;
  pokemon: StrategyPresetPokemonRef[];
}

function createSlot(input: {
  slot: number;
  pokemonSlug: string;
  abilityName: string;
  itemName: string;
  moveNames: string[];
  role: TeamRole;
  explanation: string;
}): StrategyPresetPokemonRef {
  return { ...input };
}

